// Package archdoc renders the generated package graph page from the layer model
// in internal/arch, checks the layer table of the prose page against the same
// model, and resolves every citation in docs/internals.
//
// Run "make docs-internals" after a change to the model or the tree.
package archdoc

import (
	"bytes"
	"errors"
	"fmt"
	"sort"
	"strings"

	"dm/internal/arch"
)

// DocPath is the generated page, relative to the module root.
const DocPath = "docs/internals/generated/package-graph.md"

// PagePath is the prose page that repeats the layer table, relative to the
// module root. Its table is checked against the model, not generated.
const PagePath = "docs/internals/11-layers.md"

// Render returns the content of DocPath for graph.
func Render(graph *arch.Graph) ([]byte, error) {
	if graph == nil {
		return nil, errors.New("archdoc: nil graph")
	}
	lay := newLayering(graph)
	var out bytes.Buffer
	writeSummary(&out, graph, lay)
	writeLayers(&out)
	writeDiagram(&out, lay)
	writeEdges(&out, graph, lay)
	writeSeeAlso(&out)
	return out.Bytes(), nil
}

// writeSummary writes the title, the provenance line and the totals.
func writeSummary(out *bytes.Buffer, graph *arch.Graph, lay layering) {
	out.WriteString("# Package graph\n\n")
	out.WriteString("*Generated by `internal/archdoc` from the layer model in `internal/arch/arch.go`. ")
	out.WriteString("Do not edit this file. Run `make docs-internals` to rewrite it.*\n\n")
	fmt.Fprintf(out, "%d packages, %d of them under `internal/`. %d import edges between them.\n",
		len(graph.Packages), countInternal(graph), len(lay.edges))
	if outside := outsideInternal(graph); len(outside) > 0 {
		fmt.Fprintf(out, "Outside `internal/` sit %s.\n", codeList(outside))
	}
	out.WriteString("\n")
}

// writeLayers writes the layer section and the table of the rule.
func writeLayers(out *bytes.Buffer) {
	out.WriteString("## Layers\n\n")
	out.WriteString("A layer is a set of packages that may import each other. The model is the\n")
	out.WriteString("list of layers in `internal/arch/arch.go#Layers`, and each layer names the\n")
	out.WriteString("layers it may import: that list is the rule. `internal/arch` turns the\n")
	out.WriteString("model into a test that fails the import which leaves the allowed shape\n")
	out.WriteString("(`internal/arch/arch_test.go#TestArchitecture`). This page is the graph that rule\n")
	out.WriteString("produces. The reason for each layer and how to add one live in\n")
	out.WriteString("[the layers page](../11-layers.md).\n\n")
	if entry, ok := arch.LayerNamed("entry"); ok {
		fmt.Fprintf(out, "`entry` is the layer of the programs: %s\n", codeList(entry.Packages))
		out.WriteString("(`main.go#main`, `cmd/esctest-harness/main.go#main`). Nothing imports a program,\n")
		out.WriteString("and a program may import every layer, so the diagram puts `entry` at the\n")
		out.WriteString("top.\n\n")
	}
	out.WriteString("The table is the rule, not the graph: a row lists the layers one layer may\n")
	out.WriteString("import, itself included, not the imports that exist today. Paths on this\n")
	out.WriteString("page drop the `dm/` module prefix, so `dm` is the root package and\n")
	out.WriteString("`blackbox` is `dm/blackbox`.\n\n")
	writeTable(out)
}

// writeDiagram writes the prose that reads the diagram and the diagram itself.
func writeDiagram(out *bytes.Buffer, lay layering) {
	out.WriteString("## The graph at layer level\n\n")
	fmt.Fprintf(out, "The module has %d import edges between its own packages. One node per\n", len(lay.edges))
	out.WriteString("package would be unreadable at a page width, so the diagram collapses the\n")
	out.WriteString("graph to layers and counts every edge. The list below the diagram names\n")
	out.WriteString("every one.\n\n")
	out.WriteString("A node reads `inside: n`: n is the number of imports whose two ends sit\n")
	out.WriteString("in that layer")
	if edge, ok := lay.firstInside(); ok {
		fmt.Fprintf(out, ", for example `%s` importing `%s` sits\ninside `%s`",
			short(edge.From), short(edge.To), lay.owner[edge.From])
	}
	out.WriteString(".\nAn arrow carries the number of imports from the layer it starts at into\n")
	out.WriteString("the layer it points at")
	if edge, ok := lay.firstCrossing(); ok {
		from, to := lay.owner[edge.From], lay.owner[edge.To]
		fmt.Fprintf(out, ": `%s` importing `%s` is one of\nthe %d imports from `%s` into `%s`",
			short(edge.From), short(edge.To), lay.cross(from, to), from, to)
	}
	out.WriteString(".\n\n")
	fmt.Fprintf(out, "A layer with no imports of its own shows `inside: 0`. Every one of the %d\n", len(lay.edges))
	out.WriteString("edges lands in exactly one node or on exactly one arrow, so nothing is\n")
	out.WriteString("counted twice. `go test ./internal/arch/...` is the gate: it reads that\n")
	out.WriteString("model, compares it with the imports in the module, and fails with the\n")
	out.WriteString("importer, the import and the rule of any import that leaves the allowed\n")
	out.WriteString("shape.\n\n")
	writeLayerMermaid(out, lay)
}

// writeEdges writes the package level edges, one importer per entry.
func writeEdges(out *bytes.Buffer, graph *arch.Graph, lay layering) {
	out.WriteString("## Every package edge\n\n")
	out.WriteString("Each line reads `importer -> imported` and lists every import of one\n")
	fmt.Fprintf(out, "package that lands in the module. Every one of the %d edges appears\n", len(lay.edges))
	out.WriteString("once below. A package with no line imports nothing else in the module;\n")
	out.WriteString("every leaf package is in that group. The imports of one line are ordered\n")
	out.WriteString("by layer, in the order of the table above.\n\n")
	out.WriteString("```\n")
	order := make(map[string]int, len(arch.Layers))
	for i, layer := range arch.Layers {
		order[layer.Name] = i
	}
	for _, pkg := range graph.Packages {
		imports := make([]string, 0, len(pkg.Imports))
		for _, imp := range pkg.Imports {
			if graph.Has(imp) {
				imports = append(imports, imp)
			}
		}
		if len(imports) == 0 {
			continue
		}
		sort.SliceStable(imports, func(i, j int) bool {
			return order[lay.owner[imports[i]]] < order[lay.owner[imports[j]]]
		})
		items := make([]string, len(imports))
		for i, imp := range imports {
			items[i] = short(imp)
		}
		writeWrapped(out, short(pkg.Path)+" -> ", items)
	}
	out.WriteString("```\n\n")
}

// writeSeeAlso writes the links at the foot of the page.
func writeSeeAlso(out *bytes.Buffer) {
	out.WriteString("## See also\n\n")
	out.WriteString("- [The layers page](../11-layers.md): the rule, the reason for each layer,\n")
	out.WriteString("  and how to add a package.\n")
	out.WriteString("- [The internals index](../README.md): the reading order and the other\n")
	out.WriteString("  pages of the internals documentation.\n")
}

// CheckTable compares the layer table of the prose page with the model. The page
// repeats the model by hand, so a stale row is a docs bug.
func CheckTable(page []byte) error {
	rows, err := tableRows(page)
	if err != nil {
		return err
	}
	if len(rows) != len(arch.Layers) {
		return fmt.Errorf("%s: the table has %d layer rows, the model has %d", PagePath, len(rows), len(arch.Layers))
	}
	for i, layer := range arch.Layers {
		row := rows[i]
		if row.name != layer.Name {
			return fmt.Errorf("%s: row %d names the layer %q, the model calls it %q",
				PagePath, i+1, row.name, layer.Name)
		}
		if want := mayImport(layer); row.mayImport != want {
			return fmt.Errorf("%s: the %s row may import %q, the model says %q",
				PagePath, layer.Name, row.mayImport, want)
		}
		if want := backticked(layer.Packages); row.packages != want {
			return fmt.Errorf("%s: the %s row lists %q, the model says %q",
				PagePath, layer.Name, row.packages, want)
		}
	}
	return nil
}

type tableRow struct {
	name      string
	mayImport string
	packages  string
}

// tableRows reads the layer table of the page. The header fixes the shape of
// every row.
func tableRows(page []byte) ([]tableRow, error) {
	const header = "| Layer | May import | Packages |"
	lines := strings.Split(string(page), "\n")
	start := -1
	for i, line := range lines {
		if strings.TrimSpace(line) == header {
			start = i + 2 // skip the header and the separator
			break
		}
	}
	if start < 0 {
		return nil, fmt.Errorf("%s: no layer table with the header %q", PagePath, header)
	}
	var rows []tableRow
	for _, line := range lines[start:] {
		line = strings.TrimSpace(line)
		if !strings.HasPrefix(line, "|") {
			break
		}
		cells := strings.Split(strings.Trim(line, "|"), "|")
		if len(cells) != 3 {
			return nil, fmt.Errorf("%s: row %q has %d cells, want 3", PagePath, line, len(cells))
		}
		rows = append(rows, tableRow{
			name:      strings.TrimSpace(cells[0]),
			mayImport: strings.TrimSpace(cells[1]),
			packages:  strings.TrimSpace(cells[2]),
		})
	}
	return rows, nil
}

func writeTable(out *bytes.Buffer) {
	out.WriteString("| Layer | May import | Packages |\n")
	out.WriteString("| --- | --- | --- |\n")
	for _, layer := range arch.Layers {
		fmt.Fprintf(out, "| %s | %s | %s |\n", layer.Name, mayImport(layer), backticked(layer.Packages))
	}
	out.WriteString("\n")
}

// layerPair is one node or one arrow of the diagram: the layer an edge starts
// in and the layer it ends in. Both ends name the same layer for an edge inside
// one layer.
type layerPair [2]string

// layering groups the internal edges by layer pair and remembers the layer of
// every package in the model. An edge that leaves a layer for a layer the model
// does not allow is absent, because the gate fails before this runs.
type layering struct {
	owner  map[string]string
	edges  []arch.Edge
	groups map[layerPair][]arch.Edge
}

func newLayering(graph *arch.Graph) layering {
	lay := layering{
		owner:  make(map[string]string),
		groups: make(map[layerPair][]arch.Edge),
	}
	for _, layer := range arch.Layers {
		for _, path := range layer.Packages {
			lay.owner[path] = layer.Name
		}
	}
	for _, edge := range graph.Edges() {
		from, okFrom := lay.owner[edge.From]
		to, okTo := lay.owner[edge.To]
		if !okFrom || !okTo {
			continue
		}
		pair := layerPair{from, to}
		lay.groups[pair] = append(lay.groups[pair], edge)
		lay.edges = append(lay.edges, edge)
	}
	return lay
}

// inside returns the number of edges whose two ends sit in the named layer.
func (l layering) inside(layer string) int {
	return len(l.groups[layerPair{layer, layer}])
}

// cross returns the number of edges that start in from and end in to.
func (l layering) cross(from, to string) int {
	return len(l.groups[layerPair{from, to}])
}

// firstInside returns the first edge in graph order whose two ends share a
// layer.
func (l layering) firstInside() (arch.Edge, bool) { return l.first(true) }

// firstCrossing returns the first edge in graph order whose two ends sit in
// different layers. The prose quotes it, so the example stays true when the
// tree moves.
func (l layering) firstCrossing() (arch.Edge, bool) { return l.first(false) }

func (l layering) first(sameLayer bool) (arch.Edge, bool) {
	for _, edge := range l.edges {
		from, okFrom := l.owner[edge.From]
		to, okTo := l.owner[edge.To]
		if !okFrom || !okTo {
			continue
		}
		if (from == to) == sameLayer {
			return edge, true
		}
	}
	return arch.Edge{}, false
}

// writeLayerMermaid draws the graph collapsed to layers. A node carries the
// layer's package count and its inside edges, the ones whose two ends sit in
// that layer. An arrow carries the edges that cross into another layer. One
// node per package would be unreadable at a page width, so the detail lives in
// the edge list.
func writeLayerMermaid(out *bytes.Buffer, lay layering) {
	out.WriteString("```mermaid\nflowchart TD\n")
	for _, layer := range arch.Layers {
		fmt.Fprintf(out, "  %s[\"%s<br/>%d packages<br/>inside: %d\"]\n",
			layer.Name, layer.Name, len(layer.Packages), lay.inside(layer.Name))
	}
	for _, layer := range arch.Layers {
		for _, target := range layer.MayImport {
			if target == layer.Name {
				continue
			}
			n := lay.cross(layer.Name, target)
			if n == 0 {
				continue
			}
			fmt.Fprintf(out, "  %s -->|%d| %s\n", layer.Name, n, target)
		}
	}
	out.WriteString("```\n\n")
}

// writeWrapped writes prefix followed by items as one comma separated list,
// breaking every line at width columns. A continuation line is indented two
// spaces.
func writeWrapped(out *bytes.Buffer, prefix string, items []string) {
	const width = 78
	line := prefix
	for i, item := range items {
		if i > 0 && len(line)+len(item)+2 > width {
			out.WriteString(line + ",\n")
			line = "  " + item
			continue
		}
		if i > 0 {
			line += ", "
		}
		line += item
	}
	out.WriteString(line + "\n")
}

// mayImport renders the layers a layer may import.
func mayImport(layer arch.Layer) string {
	if len(layer.MayImport) == 0 {
		return "nothing"
	}
	return strings.Join(layer.MayImport, ", ")
}

// backticked renders paths for a markdown table cell.
func backticked(paths []string) string {
	return strings.Join(backtickedNames(paths), ", ")
}

// codeList renders paths for prose: "`a`, `b` and `c`".
func codeList(paths []string) string {
	names := backtickedNames(paths)
	switch len(names) {
	case 0:
		return ""
	case 1:
		return names[0]
	}
	return strings.Join(names[:len(names)-1], ", ") + " and " + names[len(names)-1]
}

func backtickedNames(paths []string) []string {
	names := make([]string, len(paths))
	for i, path := range paths {
		names[i] = "`" + short(path) + "`"
	}
	return names
}

// short drops the module prefix from an import path.
func short(path string) string {
	return strings.TrimPrefix(path, arch.ModulePath+"/")
}

func countInternal(graph *arch.Graph) int {
	prefix := arch.ModulePath + "/internal/"
	n := 0
	for _, pkg := range graph.Packages {
		if strings.HasPrefix(pkg.Path, prefix) {
			n++
		}
	}
	return n
}

// outsideInternal returns the import paths of graph that sit outside
// internal/.
func outsideInternal(graph *arch.Graph) []string {
	prefix := arch.ModulePath + "/internal/"
	var out []string
	for _, pkg := range graph.Packages {
		if !strings.HasPrefix(pkg.Path, prefix) {
			out = append(out, pkg.Path)
		}
	}
	return out
}

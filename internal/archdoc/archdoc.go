// Package archdoc renders the generated package graph page from the layer model
// in internal/arch.
//
// Run "make docs-internals" after a change to the model or the tree.
package archdoc

import (
	"bytes"
	"errors"
	"fmt"
	"strings"

	"dm/internal/arch"
)

// DocPath is the generated page, relative to the module root.
const DocPath = "docs/internals/generated/package-graph.md"

// PagePath is the prose page that repeats the layer table, relative to the
// module root. Its table is checked against the model, not generated.
const PagePath = "docs/internals/11-layers.md"

// Render returns the content of DocPath for graph.
func Render(graph *arch.Graph) ([]byte, error) {
	if graph == nil {
		return nil, errors.New("archdoc: nil graph")
	}
	var out bytes.Buffer

	out.WriteString("# Package graph\n\n")
	out.WriteString("*Generated by `internal/archdoc` from the layer model in `internal/arch/arch.go`. ")
	out.WriteString("Do not edit this file. Run `make docs-internals` to rewrite it.*\n\n")
	fmt.Fprintf(&out, "%d packages. %d of them sit under `internal/`. Internal edges: %d.\n\n",
		len(graph.Packages), countInternal(graph), len(graph.Edges()))

	out.WriteString("## Layers\n\n")
	out.WriteString("A layer may import itself and every layer it names. `entry` may import the whole stack.\n\n")
	writeTable(&out)

	out.WriteString("## The graph at layer level\n\n")
	fmt.Fprintf(&out, "The tree draws %d imports. At one node per package that is a\n", len(graph.Edges()))
	out.WriteString("hairball, so this diagram collapses it to layers and counts the edges.\n")
	out.WriteString("A node carries the package count and the imports inside the layer. An\n")
	out.WriteString("arrow carries the imports leaving the layer, into the layer it points at.\n")
	out.WriteString("The table above names every package, so the counts are traceable, and\n")
	out.WriteString("`go test ./internal/arch/...` is the edge list that matters.\n\n")
	writeLayerMermaid(&out, graph)

	return out.Bytes(), nil
}

// CheckTable compares the layer table of the prose page with the model. The page
// repeats the model by hand, so a stale row is a docs bug.
func CheckTable(page []byte) error {
	rows, err := tableRows(page)
	if err != nil {
		return err
	}
	if len(rows) != len(arch.Layers) {
		return fmt.Errorf("%s: the table has %d layer rows, the model has %d", PagePath, len(rows), len(arch.Layers))
	}
	for i, layer := range arch.Layers {
		row := rows[i]
		if row.name != layer.Name {
			return fmt.Errorf("%s: row %d names the layer %q, the model calls it %q",
				PagePath, i+1, row.name, layer.Name)
		}
		if want := mayImport(layer); row.mayImport != want {
			return fmt.Errorf("%s: the %s row may import %q, the model says %q",
				PagePath, layer.Name, row.mayImport, want)
		}
		if want := backticked(layer.Packages); row.packages != want {
			return fmt.Errorf("%s: the %s row lists %q, the model says %q",
				PagePath, layer.Name, row.packages, want)
		}
	}
	return nil
}

type tableRow struct {
	name      string
	mayImport string
	packages  string
}

// tableRows reads the layer table of the page. The header fixes the shape of
// every row.
func tableRows(page []byte) ([]tableRow, error) {
	const header = "| Layer | May import | Packages |"
	lines := strings.Split(string(page), "\n")
	start := -1
	for i, line := range lines {
		if strings.TrimSpace(line) == header {
			start = i + 2 // skip the header and the separator
			break
		}
	}
	if start < 0 {
		return nil, fmt.Errorf("%s: no layer table with the header %q", PagePath, header)
	}
	var rows []tableRow
	for _, line := range lines[start:] {
		line = strings.TrimSpace(line)
		if !strings.HasPrefix(line, "|") {
			break
		}
		cells := strings.Split(strings.Trim(line, "|"), "|")
		if len(cells) != 3 {
			return nil, fmt.Errorf("%s: row %q has %d cells, want 3", PagePath, line, len(cells))
		}
		rows = append(rows, tableRow{
			name:      strings.TrimSpace(cells[0]),
			mayImport: strings.TrimSpace(cells[1]),
			packages:  strings.TrimSpace(cells[2]),
		})
	}
	return rows, nil
}

func writeTable(out *bytes.Buffer) {
	out.WriteString("| Layer | May import | Packages |\n")
	out.WriteString("| --- | --- | --- |\n")
	for _, layer := range arch.Layers {
		fmt.Fprintf(out, "| %s | %s | %s |\n", layer.Name, mayImport(layer), backticked(layer.Packages))
	}
	out.WriteString("\n")
}

// writeLayerMermaid draws the graph collapsed to layers: one node per layer with
// its package count and its internal edges, then one arrow per layer pair with
// the number of imports that cross it. A diagram with one node per package is
// 122 edges and unreadable at a page width, so the detail lives in the table.
func writeLayerMermaid(out *bytes.Buffer, graph *arch.Graph) {
	inside, crossing := layerCounts(graph)
	out.WriteString("```mermaid\nflowchart TD\n")
	for _, layer := range arch.Layers {
		fmt.Fprintf(out, "  %s[\"%s<br/>%d packages<br/>%d inside\"]\n",
			layer.Name, layer.Name, len(layer.Packages), inside[layer.Name])
	}
	for _, layer := range arch.Layers {
		for _, target := range layer.MayImport {
			n := crossing[[2]string{layer.Name, target}]
			if n == 0 || target == layer.Name {
				continue
			}
			fmt.Fprintf(out, "  %s -->|%d| %s\n", layer.Name, n, target)
		}
	}
	out.WriteString("```\n")
}

// layerCounts splits the internal edges into the ones inside a layer and the
// ones that cross into another. An edge that leaves a layer for a layer the
// model does not allow is invisible here, because the gate fails before this
// runs.
func layerCounts(graph *arch.Graph) (inside map[string]int, crossing map[[2]string]int) {
	owner := make(map[string]string, len(graph.Packages))
	for _, layer := range arch.Layers {
		for _, path := range layer.Packages {
			owner[path] = layer.Name
		}
	}
	inside = make(map[string]int, len(arch.Layers))
	crossing = make(map[[2]string]int)
	for _, edge := range graph.Edges() {
		from, okFrom := owner[edge.From]
		to, okTo := owner[edge.To]
		if !okFrom || !okTo {
			continue
		}
		if from == to {
			inside[from]++
			continue
		}
		crossing[[2]string{from, to}]++
	}
	return inside, crossing
}

// mayImport renders the layers a layer may import.
func mayImport(layer arch.Layer) string {
	if len(layer.MayImport) == 0 {
		return "nothing"
	}
	return strings.Join(layer.MayImport, ", ")
}

// backticked renders paths for a markdown table cell.
func backticked(paths []string) string {
	quoted := make([]string, len(paths))
	for i, path := range paths {
		quoted[i] = "`" + short(path) + "`"
	}
	return strings.Join(quoted, ", ")
}

// short drops the module prefix from an import path.
func short(path string) string {
	return strings.TrimPrefix(path, arch.ModulePath+"/")
}

func countInternal(graph *arch.Graph) int {
	prefix := arch.ModulePath + "/internal/"
	n := 0
	for _, pkg := range graph.Packages {
		if strings.HasPrefix(pkg.Path, prefix) {
			n++
		}
	}
	return n
}
